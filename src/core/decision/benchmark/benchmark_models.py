"""Immutable Pydantic models for Decision Benchmarking & Evaluation Framework (M4.5)."""

from typing import Any

from pydantic import BaseModel, ConfigDict, Field, PrivateAttr, model_validator

from src.core.decision.decision_models import DecisionContext, DecisionResult


class DecisionBenchmarkItem(BaseModel):
    """Immutable single benchmark evaluation item containing context and expected outcome."""

    item_id: str = Field(..., min_length=1)
    context: DecisionContext = Field(...)
    expected_action: str = Field(..., min_length=1)

    model_config = ConfigDict(frozen=True, arbitrary_types_allowed=True)


class DecisionBenchmarkDataset(BaseModel):
    """Immutable collection of benchmark evaluation items."""

    dataset_id: str = Field(..., min_length=1)
    items: tuple[DecisionBenchmarkItem, ...] = Field(..., min_length=1)

    model_config = ConfigDict(frozen=True)


class DecisionBenchmarkSuite(BaseModel):
    """Immutable benchmark suite tying a dataset and configuration together."""

    suite_id: str = Field(..., min_length=1)
    dataset: DecisionBenchmarkDataset = Field(...)
    execution_config: dict[str, Any] = Field(default_factory=dict)
    metadata: dict[str, Any] = Field(default_factory=dict)

    model_config = ConfigDict(frozen=True)


class DecisionBenchmarkRawOutput(BaseModel):
    """Immutable raw outputs generated by executing a benchmark suite."""

    suite_id: str = Field(..., min_length=1)
    item_ids: tuple[str, ...] = Field(default_factory=tuple)
    expected_actions: tuple[str, ...] = Field(default_factory=tuple)
    actual_actions: tuple[str, ...] = Field(default_factory=tuple)
    latencies_ms: tuple[float, ...] = Field(default_factory=tuple)
    decisions: tuple[DecisionResult, ...] = Field(default_factory=tuple)

    model_config = ConfigDict(frozen=True)


class DecisionBenchmarkMetrics(BaseModel):
    """Strongly typed immutable decision benchmark metrics."""

    accuracy: float = Field(..., ge=0.0, le=1.0)
    abstention_rate: float = Field(..., ge=0.0, le=1.0)
    escalation_rate: float = Field(..., ge=0.0, le=1.0)
    mean_latency_ms: float = Field(..., ge=0.0)
    throughput_qps: float = Field(..., ge=0.0)

    model_config = ConfigDict(frozen=True)


class DecisionBenchmarkResult(BaseModel):
    """Immutable result of a benchmark run containing metrics and stats."""

    suite_id: str = Field(..., min_length=1)
    metrics: DecisionBenchmarkMetrics = Field(...)
    latency_stats: dict[str, float] = Field(default_factory=dict)
    success: bool = Field(default=True)
    metadata: dict[str, Any] = Field(default_factory=dict)

    model_config = ConfigDict(frozen=True)


class DecisionBenchmarkReport(BaseModel):
    """Immutable final report documenting benchmark run metadata and outcomes."""

    suite_id: str = Field(..., min_length=1)
    result: DecisionBenchmarkResult = Field(...)
    profile_id: str = Field(..., min_length=1)
    timestamp: str = Field(..., min_length=1)

    model_config = ConfigDict(frozen=True)


class DecisionBenchmarkProfile(BaseModel):
    """Immutable profile defining benchmark evaluation scope."""

    profile_id: str = Field(..., min_length=1)
    enabled_metrics: tuple[str, ...] = Field(default_factory=tuple)
    suite_id: str = Field(..., min_length=1)

    model_config = ConfigDict(frozen=True)


class DecisionBenchmarkProfileRegistry(BaseModel):
    """O(1) registry for benchmark profiles with duplicate and compatibility checks."""

    profiles: tuple[DecisionBenchmarkProfile, ...] = Field(..., min_length=1)

    _profile_index: dict[str, DecisionBenchmarkProfile] = PrivateAttr(
        default_factory=dict
    )

    model_config = ConfigDict(frozen=True)

    @model_validator(mode="after")
    def _build_and_validate_index(self) -> "DecisionBenchmarkProfileRegistry":
        from src.core.exceptions import DuplicateDecisionBenchmarkProfileError

        index: dict[str, DecisionBenchmarkProfile] = {}
        for p in self.profiles:
            profile_id = p.profile_id
            if profile_id in index:
                raise DuplicateDecisionBenchmarkProfileError(
                    f"Duplicate benchmark profile ID detected: {profile_id}"
                )
            index[profile_id] = p
        object.__setattr__(self, "_profile_index", index)
        return self

    def resolve(self, profile_id: str) -> DecisionBenchmarkProfile:
        from src.core.exceptions import DecisionBenchmarkProfileNotFoundError

        if profile_id not in self._profile_index:
            raise DecisionBenchmarkProfileNotFoundError(
                f"Decision benchmark profile not found: {profile_id}"
            )
        return self._profile_index[profile_id]

    def validate_compatibility(self, suite_id: str) -> None:
        """Validates that a profile is registered for the specified suite_id."""
        for p in self.profiles:
            if p.suite_id == suite_id:
                return
        from src.core.exceptions import DecisionBenchmarkProfileNotFoundError

        raise DecisionBenchmarkProfileNotFoundError(
            f"No benchmark profile configured for suite ID: {suite_id}"
        )
